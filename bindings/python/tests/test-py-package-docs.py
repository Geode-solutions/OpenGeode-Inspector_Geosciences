"""Checks that the documentation of the package is correct: the examples are
executed as doctests, every module has a docstring, and the generated
__init__.py of the wheel carries the same text.

Arguments: the text file of the documentation, the wheel package directory
generated by CMake."""

import ast
import doctest
import io
import os
import sys

import geode_test_env


def check(condition, message):
    if not condition:
        raise ValueError("[Test] " + message)


def run_examples(documentation):
    parser = doctest.DocTestParser()
    test = parser.get_doctest(
        documentation, {}, "opengeode_inspector_geosciences", None, 0
    )
    check(len(test.examples) >= 20, f"Only {len(test.examples)} examples")
    output = io.StringIO()
    runner = doctest.DocTestRunner(verbose=False, optionflags=doctest.ELLIPSIS)
    runner.run(test, out=output.write)
    results = runner.summarize(verbose=False)
    check(
        results.failed == 0,
        f"{results.failed} example(s) failed:\n{output.getvalue()}",
    )


def check_docstrings(documentation):
    import opengeode_inspector_geosciences
    import opengeode_inspector_geosciences_py_inspection as extension
    import geosciences_inspection

    check(opengeode_inspector_geosciences.__doc__ == documentation, "Wrong __doc__")
    for module in [geosciences_inspection, extension]:
        check(
            module.__doc__ and len(module.__doc__) > 40,
            f"No docstring in {module.__name__}",
        )
    library = extension.OpenGeodeInspectorGeosciencesInspectionLibrary
    check(library.__doc__, "No docstring for the library")
    check(library.initialize.__doc__, "No docstring for the library initialize")


def check_wheel_init(documentation, wheel_directory):
    init = os.path.join(wheel_directory, "__init__.py")
    with open(init, encoding="utf-8") as file:
        content = file.read()
    check(
        ast.get_docstring(ast.parse(content), clean=False) == documentation,
        "Wrong __init__.py docstring",
    )
    path = os.path.join(wheel_directory, "geosciences_inspection.py")
    with open(path, encoding="utf-8") as file:
        module = ast.parse(file.read())
    check(ast.get_docstring(module), "No docstring in the wheel module")


if __name__ == "__main__":
    with open(sys.argv[1], encoding="utf-8") as file:
        documentation = file.read()
    run_examples(documentation)
    check_docstrings(documentation)
    check_wheel_init(documentation, sys.argv[2])
